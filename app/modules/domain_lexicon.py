def strip_unicode_artifacts(text: str) -> str:
    """Strips foreign script bleed (e.g. Bengali Unicode block) and control symbols."""
    if not text:
        return ""
    cleaned = re.sub(r"[\u0980-\u09FF\uFFFD]", "", text)
    cleaned = re.sub(r"^[^\w\u0900-\u097F]+$", "", cleaned)
    return cleaned.strip()


def clean_repetitive_ngrams(text: str) -> str:
    """Eliminates degenerate token repetition loops from NMT output."""
    pattern = r"(\b.{4,40}?\b)(?:\s*\1){2,}"
    cleaned = re.sub(pattern, r"\1", text, flags=re.IGNORECASE)
    return cleaned


def normalize_marathi_text(text: str) -> str:
    """Cleans phonetic Whisper ASR Marathi output prior to IndicTrans2 translation."""
    if not text or not isinstance(text, str):
        return ""

    cleaned = strip_unicode_artifacts(text)
    for pattern, replacement in MARATHI_DOMAIN_LEXICON:
        cleaned = re.sub(pattern, replacement, cleaned, flags=re.IGNORECASE)

    cleaned = re.sub(r"\s+", " ", cleaned)
    cleaned = re.sub(r"[^\w\s\u0900-\u097Fa-zA-Z0-9.,!?/%:()\'\"-]", "", cleaned).strip()
    return cleaned


def normalize_hindi_text(text: str) -> str:
    """Post-cleans translated Hindi text to intercept and replace NMT hallucinations."""
    if not text or not isinstance(text, str):
        return ""

    cleaned = clean_repetitive_ngrams(text)
    for pattern, replacement in HINDI_POST_TRANSLATION_CLEANUP:
        cleaned = re.sub(pattern, replacement, cleaned, flags=re.IGNORECASE)

    cleaned = re.sub(r"\s+", " ", cleaned)
    return cleaned.strip()


def normalize_text(text: str, lang: str = "mr") -> str:
    """Unified dispatcher for pipeline text normalization."""
    if lang == "mr":
        return normalize_marathi_text(text)
    if lang == "hi":
        return normalize_hindi_text(text)
    return text.strip()